import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {productionDependencyFilter} from '../src/productionDependencyFilter.js';
import {stageNative} from './stage-native.js';
const require=createRequire(import.meta.url),root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {StandalonePackager}=require('jade-build-tools/standalone-packager');
const {inject}=require('postject');
const lock=JSON.parse(fs.readFileSync(path.join(root,'package-lock.json'),'utf8'));
stageNative();
new StandalonePackager({root,distributionName:'jade-mcp-win-x64',executableName:'jade-mcp.exe',entrypoint:'bin/jade-mcp.js',moduleType:'module',runtimeFolders:['bin','src','native','node_modules'],runtimeFiles:['package.json','README.md','ThirdPartyNotices.txt','docs/architecture.drawio','docs/architecture.drawio.svg'],nodeLicense:'node_modules/jade-build-tools/licenses/node-v24.22.1-LICENSE.txt',copyFilter:productionDependencyFilter(lock)}).build({inject}).catch(error=>{console.error(error.message);process.exitCode=1;});
